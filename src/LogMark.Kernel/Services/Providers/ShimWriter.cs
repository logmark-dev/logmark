using System.Text;

namespace LogMark.Services.Providers;

/// <summary>
/// Generates the stable hook shim: a fixed-path launcher that hook configs
/// reference instead of any build-specific binary path. Content is a ranked
/// candidate chain with liveness checks, regenerated idempotently on every
/// product startup, so wired configs never go stale. Written in both cmd and
/// sh form; hook entries reference the .cmd on Windows (cmd and Git Bash both
/// execute it) and the sh form elsewhere - with ONE exception: a WSL-hosted
/// framework runs its hooks inside Linux, so its hook entry references
/// <see cref="ShShimPath"/> in Linux form even though the wiring runs on
/// Windows. See HooksService.ResolveHookCommandPath.
/// </summary>
public sealed class ShimWriter
{
    private readonly string _binDir;
    public ShimWriter(string binDir) => _binDir = binDir;

    /// <summary>
    /// Live shim directory. Honors <c>LOGMARK_APPDATA_PATH</c> (one sandbox
    /// root for all machine-local coordination state - see
    /// ProviderManifestStore.DefaultRoot) even though the live location is
    /// LOCALAPPDATA rather than APPDATA: a sandboxed run wants everything
    /// under its one redirected root.
    /// </summary>
    public static string DefaultBinDir()
    {
        var overrideRoot = Environment.GetEnvironmentVariable("LOGMARK_APPDATA_PATH");
        if (!string.IsNullOrEmpty(overrideRoot))
            return Path.Combine(overrideRoot, "bin");
        return OperatingSystem.IsWindows()
            ? Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "LogMark", "bin")
            : Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".logmark", "bin");
    }

    /// <summary>
    /// The shim path for the CURRENT host: the .cmd twin on Windows (cmd and
    /// Git Bash both execute it), the extension-less sh twin elsewhere. This
    /// is what the five Windows-hosted frameworks get wired to, and it is
    /// deliberately NOT what a WSL-hosted framework gets - see
    /// <see cref="ShShimPath"/>.
    /// </summary>
    public static string CliShimPath() => OperatingSystem.IsWindows()
        ? Path.Combine(DefaultBinDir(), "logmark-run.cmd")
        : ShShimPath();

    /// <summary>
    /// The sh twin, always the extension-less <c>logmark-run</c>, regardless
    /// of the host OS. A WSL-hosted agent executes hooks INSIDE Linux, where
    /// neither the ".cmd" filename nor the Windows path form means anything -
    /// so its hook command must be this file, named without the extension and
    /// converted to Linux form by the caller
    /// (<c>WslBridge.ToLinuxPath</c> -&gt;
    /// <c>/mnt/c/Users/&lt;user&gt;/AppData/Local/LogMark/bin/logmark-run</c>).
    ///
    /// Added during the final whole-feature review (2026-07-31): HooksService
    /// interpolated CliShimPath() verbatim for every framework, so grok's
    /// WSL-side hook file received
    /// <c>"C:\...\logmark-run.cmd" agent-capture --framework grok</c> and
    /// exited 127 (command not found) on every SessionEnd and PreCompact -
    /// which made this whole WriteSh WSL branch unreachable in production.
    /// Exposed as an accessor rather than string-munging the ".cmd" off
    /// CliShimPath() at the call site, so the two filenames stay owned here.
    /// </summary>
    public static string ShShimPath() => Path.Combine(DefaultBinDir(), "logmark-run");

    public void WriteCliShim(IReadOnlyList<ResolvedProvider> rankedCli)
    {
        Directory.CreateDirectory(_binDir);
        WriteCmd(rankedCli);
        WriteSh(rankedCli);
    }

    private void WriteCmd(IReadOnlyList<ResolvedProvider> ranked)
    {
        const string CrLf = "\r\n";
        var sb = new StringBuilder();
        sb.Append("@echo off" + CrLf);
        sb.Append("rem Generated by LogMark - do not edit. Regenerated on every product startup." + CrLf);
        sb.Append("rem shim-version: 1" + CrLf);
        for (var i = 0; i < ranked.Count; i++)
            sb.Append($"if exist \"{ranked[i].Path}\" goto c{i}" + CrLf);
        sb.Append("echo logmark-run: no LogMark installation found. Reinstall LogMark. 1>&2" + CrLf);
        sb.Append("exit /b 1" + CrLf);
        for (var i = 0; i < ranked.Count; i++)
        {
            var prefix = ranked[i].PrefixArgs.Count > 0 ? " " + string.Join(' ', ranked[i].PrefixArgs) : "";
            sb.Append($":c{i}" + CrLf);
            sb.Append($"\"{ranked[i].Path}\"{prefix} %*" + CrLf);
            sb.Append("exit /b %errorlevel%" + CrLf);
        }
        File.WriteAllText(Path.Combine(_binDir, "logmark-run.cmd"), sb.ToString());
    }

    /// <summary>
    /// The sh twin serves two callers: a native POSIX LogMark install, and a
    /// WSL-hosted agent reaching a Windows install across the boundary. For
    /// the second case a Windows candidate path is unusable verbatim, so each
    /// candidate is emitted in both forms and the WSL branch additionally
    /// rewrites the hook payload: grok sends a Linux cwd and transcriptPath
    /// that the Windows binary cannot open, and a camelCase envelope whose
    /// keys lm.exe does not read.
    ///
    /// The Windows-to-WSL-mount form (e.g. C:\LogMark\lm.exe -&gt;
    /// /mnt/c/LogMark/lm.exe) is computed here in C#, not by a runtime sed
    /// pass over the candidate path in the generated script: the candidate
    /// paths are fully known at generation time, so there is nothing to
    /// translate at runtime, and a runtime sed/backslash pipeline is exactly
    /// the kind of double-escaped, hard-to-verify shell code this shim
    /// should avoid. Only the hook *payload* (cwd/transcriptPath, arriving
    /// on stdin from the caller) is a genuinely runtime value and needs a
    /// runtime tool (wslpath) below.
    ///
    /// Deviation from the fail-open contract: grok's hooks are fail-open by
    /// design, so under WSL a translation failure or missing install still
    /// exits 0 rather than failing the caller's turn. But this script also
    /// serves native POSIX LogMark installs directly (no WSL involved), and
    /// for that caller a missing install is a real, actionable problem -
    /// silently exiting 0 there would hide a genuinely broken installation
    /// from every framework wired to it, not just grok. So the not-found
    /// exit code is narrowed to the WSL case only: diagnostic to stderr
    /// always, then exit 0 under WSL, exit 1 otherwise.
    /// </summary>
    private void WriteSh(IReadOnlyList<ResolvedProvider> ranked)
    {
        var sb = new StringBuilder();
        sb.Append("#!/bin/sh\n");
        sb.Append("# Generated by LogMark - do not edit. Regenerated on every product startup.\n");
        sb.Append("# shim-version: 3\n");
        sb.Append("\n");
        sb.Append("lm_is_wsl() { [ -n \"$WSL_DISTRO_NAME\" ] || grep -qi microsoft /proc/version 2>/dev/null; }\n");
        sb.Append("\n");
        sb.Append("# Hook payload arrives on stdin. Under WSL, translate the paths the\n");
        sb.Append("# Windows binary must open and normalize camelCase to snake_case.\n");
        sb.Append("# Slurping stdin is a WSL-only behaviour: every other caller keeps the\n");
        sb.Append("# direct stdin inheritance an exec gives (see lm_dispatch below).\n");
        sb.Append("lm_payload=\"\"\n");
        sb.Append("lm_slurped=0\n");
        sb.Append("if lm_is_wsl && [ ! -t 0 ]; then lm_payload=$(cat); lm_slurped=1; fi\n");
        sb.Append("if [ \"$lm_slurped\" = 1 ] && [ -n \"$lm_payload\" ]; then\n");
        sb.Append("  if command -v jq >/dev/null 2>&1; then\n");
        sb.Append("    lm_cwd=$(printf '%s' \"$lm_payload\" | jq -r '.cwd // .workspaceRoot // empty' 2>/dev/null)\n");
        sb.Append("    [ -z \"$lm_cwd\" ] && lm_cwd=$(pwd)\n");
        sb.Append("    lm_wcwd=$(wslpath -w \"$lm_cwd\" 2>/dev/null)\n");
        sb.Append("    lm_tp=$(printf '%s' \"$lm_payload\" | jq -r '.transcriptPath // .transcript_path // empty' 2>/dev/null)\n");
        sb.Append("    lm_wtp=\"\"\n");
        sb.Append("    [ -n \"$lm_tp\" ] && lm_wtp=$(wslpath -w \"$lm_tp\" 2>/dev/null)\n");
        sb.Append("    lm_translated=$(printf '%s' \"$lm_payload\" | jq -c \\\n");
        sb.Append("      --arg cwd \"$lm_wcwd\" --arg tp \"$lm_wtp\" \\\n");
        sb.Append("      '. + {cwd: (if $cwd == \"\" then .cwd else $cwd end),\n");
        sb.Append("            session_id: (.sessionId // .session_id),\n");
        sb.Append("            hook_event_name: (.hookEventName // .hook_event_name),\n");
        sb.Append("            transcript_path: (if $tp == \"\" then (.transcript_path // \"\") else $tp end)}\n");
        // The camelCase originals are DELETED, not merely shadowed. jq's
        // ". + {...}" only ADDS keys, so the untranslated Linux transcriptPath
        // used to survive alongside the translated snake_case one - a stale,
        // wrong-form path sitting in the envelope waiting for a reader to pick
        // the wrong key, which is exactly how C3 got in. Normalizing to ONE
        // canonical spelling also makes the shim-to-HookProfile contract
        // testable: a profile that declares the camelCase names now fails
        // outright instead of silently reading the wrong value.
        sb.Append("       | del(.sessionId, .hookEventName, .transcriptPath)' 2>/dev/null)\n");
        sb.Append("    [ -n \"$lm_translated\" ] && lm_payload=\"$lm_translated\"\n");
        sb.Append("  else\n");
        // jq is a hard dependency of this branch (documented in
        // docs/reference/agent-hook-capability-matrix.md). Without it the
        // payload reaches lm.exe with Linux paths and camelCase keys, and
        // capture silently writes nothing. Say so on stderr rather than
        // degrading in silence; the hook still stays fail-open (the exit code
        // is whatever the dispatched binary returns, and the not-found tail
        // below still exits 0 under WSL).
        sb.Append("    echo \"logmark-run: jq not found - hook payload passed through untranslated;\" >&2\n");
        sb.Append("    echo \"logmark-run: install jq inside this distro (apt install jq) to enable LogMark capture.\" >&2\n");
        sb.Append("  fi\n");
        sb.Append("fi\n");
        sb.Append("\n");
        // Non-WSL callers keep exec: the process is REPLACED, so stdin is
        // inherited directly (a pipe that stays open never blocks in `cat`,
        // NUL bytes are not truncated, trailing newlines are not stripped)
        // and the replacement's exit status becomes the shim's verbatim.
        sb.Append("lm_dispatch() {\n");
        sb.Append("  if [ \"$lm_slurped\" = 1 ]; then printf '%s' \"$lm_payload\" | \"$@\"; else exec \"$@\"; fi\n");
        sb.Append("}\n");
        sb.Append("\n");
        // Each check has two distinct outcomes that must never be conflated:
        // the candidate does not exist (fall through to the next candidate,
        // or eventually the not-found tail), vs. the candidate exists and was
        // run (its exit code - success OR failure - is final and must
        // propagate verbatim; it must never fall through to the next
        // candidate or to the not-found tail). A bare `&& exit 0` cannot
        // express this: it only takes the "exit 0" branch on success, so a
        // found binary that runs and fails would otherwise fall through and
        // get misreported as "no LogMark installation found". The `{ ...;
        // exit $?; }` group runs unconditionally once `[ -e ]` is true and
        // always exits with the real status, whatever it is.
        foreach (var r in ranked)
        {
            var prefix = r.PrefixArgs.Count > 0 ? " " + string.Join(' ', r.PrefixArgs) : "";
            sb.Append($"[ -e \"{r.Path}\" ] && {{ lm_dispatch \"{r.Path}\"{prefix} \"$@\"; exit $?; }}\n");
            var mnt = ToWslMountForm(r.Path);
            if (mnt is not null)
                sb.Append($"[ -e \"{mnt}\" ] && {{ lm_dispatch \"{mnt}\"{prefix} \"$@\"; exit $?; }}\n");
        }
        sb.Append("echo \"logmark-run: no LogMark installation found. Reinstall LogMark.\" >&2\n");
        sb.Append("lm_is_wsl && exit 0\n");
        sb.Append("exit 1\n");

        var path = Path.Combine(_binDir, "logmark-run");
        File.WriteAllText(path, sb.ToString());
        if (!OperatingSystem.IsWindows())
            File.SetUnixFileMode(path, UnixFileMode.UserRead | UnixFileMode.UserWrite
                | UnixFileMode.UserExecute | UnixFileMode.GroupRead | UnixFileMode.GroupExecute
                | UnixFileMode.OtherRead | UnixFileMode.OtherExecute);
    }

    /// <summary>
    /// Windows absolute path (drive letter + colon) to its WSL mount-point
    /// form: <c>C:\LogMark\lm.exe</c> -&gt; <c>/mnt/c/LogMark/lm.exe</c>.
    /// Returns null for paths that are not a Windows drive path (already
    /// POSIX, UNC, relative, etc.) - those have no WSL mount candidate.
    ///
    /// Assumption and its limit: this hardcodes the WSL2 default automount
    /// root <c>/mnt/&lt;drive&gt;</c>. It is computed here on the Windows
    /// side at shim-generation time, which has no visibility into the WSL
    /// guest's <c>/etc/wsl.conf</c> - a guest with a customized
    /// <c>[automount] root</c> (e.g. <c>/c/</c> instead of <c>/mnt/c/</c>,
    /// rare in practice) makes this candidate's <c>[ -e ]</c> check simply
    /// fail closed (falls through, no crash). This is not a regression:
    /// the plan brief's own runtime <c>sed</c> pass hardcoded the same
    /// <c>/mnt/</c> prefix, so the assumption already existed; only where it
    /// is computed moved. Regenerating the shim on every startup does not
    /// mitigate this either, since regeneration also runs on the Windows
    /// side and is equally blind to the guest's mount config. By contrast,
    /// the hook *payload*'s cwd/transcriptPath conversion (the <c>wslpath
    /// -w</c> calls above) is deliberately left as a runtime call inside the
    /// WSL guest, where it does reflect the guest's actual mount
    /// configuration - that asymmetry is intentional, not an oversight.
    /// </summary>
    private static string? ToWslMountForm(string candidatePath)
    {
        if (candidatePath.Length < 3 || candidatePath[1] != ':' || !char.IsLetter(candidatePath[0]))
            return null;
        var drive = char.ToLowerInvariant(candidatePath[0]);
        var rest = candidatePath[2..].Replace('\\', '/');
        return $"/mnt/{drive}{rest}";
    }
}
